def format_article_for_indexing(article: LegalArticle) -> Dict[str, Any]:
    """将法律条文格式化为知识库索引格式"""
    return {
        "title": f"《{article.law_name}》{article.article_number} {article.title}",
        "content": f"《{article.law_name}》{article.article_number}（{article.title}）\n\n{article.content}",
        "source": article.law_name,
        "metadata": {
            "law_name": article.law_name,
            "law_type": article.law_type,
            "article_number": article.article_number,
            "chapter": article.chapter,
            "effective_date": article.effective_date,
            "issuing_authority": article.issuing_authority,
            "tags": article.tags,
        }
    }


def format_articles_for_rag_context(articles: List[LegalArticle], max_length: int = 4000) -> str:
    """将检索到的法律条文格式化为RAG上下文"""
    context_parts = []
    total_len = 0

    for art in articles:
        entry = f"【{art.law_name} {art.article_number}】{art.title}\n{art.content}\n"
        if total_len + len(entry) > max_length:
            break
        context_parts.append(entry)
        total_len += len(entry)

    return "\n".join(context_parts)
